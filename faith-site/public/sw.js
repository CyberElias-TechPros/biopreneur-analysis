/*
  Service worker — offline reading, not an app cache.

  Three rules, in order:
    1. Never serve a stale HTML page to someone online. HTML is network-first.
    2. Always serve immutable assets from cache (hashed filenames never change).
    3. Never cache a 404 or a redirect, and never cache ads or analytics.

  A cached teaching is the whole point: readers in poor-connectivity regions
  should be able to open a page they already visited without a network, and the
  Listening Room keeps working because speech is generated by the device.
*/

const VERSION = 'lijn-v1';
const HTML_CACHE = `${VERSION}-html`;
const ASSET_CACHE = `${VERSION}-assets`;
const OFFLINE_URL = '/offline.html';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(HTML_CACHE).then((cache) =>
      cache.addAll([OFFLINE_URL]).catch(() => {
        /* offline page may be missing in a partial deploy — never block install */
      })
    )
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => !k.startsWith(VERSION)).map((k) => caches.delete(k)))
      )
      .then(() => self.clients.claim())
  );
});

function isCacheableAsset(url) {
  return (
    url.origin === self.location.origin &&
    (url.pathname.startsWith('/_astro/') ||
      url.pathname.startsWith('/fonts/') ||
      url.pathname.startsWith('/images/') ||
      url.pathname === '/manifest.webmanifest' ||
      url.pathname === '/favicon.svg')
  );
}

function isNavigable(request) {
  return request.mode === 'navigate' && request.method === 'GET';
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Third-party (ads, fonts CDNs, translation) are never intercepted.
  if (url.origin !== self.location.origin) return;

  if (isCacheableAsset(url)) {
    event.respondWith(
      caches.open(ASSET_CACHE).then(async (cache) => {
        const hit = await cache.match(request);
        if (hit) return hit;
        const response = await fetch(request);
        if (response.ok) cache.put(request, response.clone());
        return response;
      })
    );
    return;
  }

  if (isNavigable(request)) {
    event.respondWith(
      (async () => {
        try {
          const response = await fetch(request);
          if (response.ok && response.status === 200) {
            const cache = await caches.open(HTML_CACHE);
            cache.put(request, response.clone());
          }
          return response;
        } catch (err) {
          const cached = await caches.match(request);
          if (cached) return cached;
          const offline = await caches.match(OFFLINE_URL);
          if (offline) return offline;
          throw err;
        }
      })()
    );
  }
});

// Let a page ask to clear its own cache (used by the offline page).
self.addEventListener('message', (event) => {
  if (event.data === 'clear-cache') {
    event.waitUntil(
      caches.keys().then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
    );
  }
});
