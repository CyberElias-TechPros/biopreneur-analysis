import type { APIContext } from 'astro';
import { getCollection } from 'astro:content';
import { CATEGORIES } from '../data/categories';
import { routeMetaFor } from '../lib/sitemap-routes';

/**
 * A single flat sitemap at /sitemap.xml.
 *
 * @astrojs/sitemap still emits sitemap-index.xml + sitemap-0.xml for crawlers
 * that expect an index. This route exists because /sitemap.xml is the address
 * most people type, the one a default Search Console setup looks for, and the
 * one third-party SEO tools probe first — so it should answer with a real
 * sitemap rather than a 404.
 *
 * URLs and priority/lastmod come from the same policy helpers the integration
 * uses, so the flat file and the indexed files cannot drift apart.
 */

const STATIC_ROUTES: Array<{ path: string; changefreq: string; priority: string }> = [
  { path: '/', changefreq: 'daily', priority: '1.0' },
  { path: '/teachings/', changefreq: 'daily', priority: '0.9' },
  { path: '/community/', changefreq: 'monthly', priority: '0.6' },
  { path: '/slate/', changefreq: 'weekly', priority: '0.7' },
  { path: '/glossary/', changefreq: 'monthly', priority: '0.7' },
  { path: '/about/', changefreq: 'yearly', priority: '0.5' },
  { path: '/doctrinal-basis/', changefreq: 'yearly', priority: '0.5' },
  { path: '/contact/', changefreq: 'yearly', priority: '0.5' },
  { path: '/privacy/', changefreq: 'yearly', priority: '0.3' },
];

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function isoDay(value: unknown): string {
  if (typeof value === 'string' && /^\d{4}-\d{2}-\d{2}/.test(value)) {
    return value.slice(0, 10);
  }
  const date = value instanceof Date ? value : new Date(String(value));
  return Number.isNaN(date.getTime())
    ? new Date().toISOString().slice(0, 10)
    : date.toISOString().slice(0, 10);
}

export async function GET(context: APIContext) {
  const origin = (context.site ?? new URL('https://lij.name.ng'))
    .toString()
    .replace(/\/$/, '');

  const entries: string[] = [];
  let latest = '';

  const push = (path: string, lastmod: string, changefreq: string, priority: string) => {
    if (lastmod > latest) latest = lastmod;
    entries.push(
      `  <url>\n` +
        `    <loc>${escapeXml(origin + path)}</loc>\n` +
        `    <lastmod>${lastmod}</lastmod>\n` +
        `    <changefreq>${changefreq}</changefreq>\n` +
        `    <priority>${priority}</priority>\n` +
        `  </url>`
    );
  };

  // Static pages first, so the home page leads the document.
  for (const route of STATIC_ROUTES) {
    const meta = routeMetaFor(origin + route.path);
    push(
      route.path,
      meta.lastmod ?? new Date().toISOString().slice(0, 10),
      route.changefreq,
      route.priority
    );
  }

  // Articles, newest first. Built pages only — a URL appears here exactly when
  // a page for it was generated.
  const articles = await getCollection('articles');
  const sorted = [...articles].sort(
    (a, b) => new Date(b.data.pubDate).getTime() - new Date(a.data.pubDate).getTime()
  );

  for (const article of sorted) {
    const lastmod = isoDay(article.data.updatedDate ?? article.data.pubDate);
    push(`/${article.data.slug}/`, lastmod, 'monthly', '0.9');
  }

  // Every category hub is generated by src/pages/category/[slug].astro from the
  // same CATEGORIES list, so every hub is a real page and belongs here.
  for (const category of CATEGORIES) {
    push(`/category/${category.slug}/`, latest, 'weekly', '0.8');
  }

  const body =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    entries.join('\n') +
    `\n</urlset>\n`;

  return new Response(body, {
    headers: {
      'Content-Type': 'application/xml; charset=utf-8',
      'Cache-Control': 'public, max-age=3600',
    },
  });
}
